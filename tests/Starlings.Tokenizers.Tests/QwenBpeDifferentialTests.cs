using System.IO.Compression;
using System.Text;
using System.Text.Json;
using Xunit.Sdk;

namespace Starlings.Tokenizers.Tests;

/// <summary>
/// Randomized differential test against huggingface/tokenizers 0.23.2 (the Rust implementation,
/// through its Python binding). The dumps hold seeded generated strings (scripts, astral planes,
/// whitespace and newline runs, combining marks, contractions, added-token literals and fragments,
/// any scalar value) with the reference ids, offsets and decode, on the profile asset and on option
/// variants that reach interpreter branches the asset leaves unused, plus random id sequences for
/// decode. Generated by reference/qwen-bpe/run_qwen_bpe_tokenizer.py --differential-out.
/// </summary>
/// <remarks>
/// The committed dumps (<c>TestData/qwen-bpe/&lt;profile&gt;/differential.jsonl.gz</c>, 1,500 strings,
/// 300 per variant, 500 decodes, seed 20261010) always run. Larger dumps are kept outside Git: set
/// <c>STARLING_QWEN_DIFFERENTIAL_DIR</c> to a directory of <c>&lt;profile&gt;-*.jsonl.gz</c> files from the
/// same runner and they run too.
/// </remarks>
public class QwenBpeDifferentialTests(ITestOutputHelper output)
{
    [Theory]
    [InlineData("kev")]
    [InlineData("chat")]
    public void MatchesReferenceOnCommittedDump(string profile)
    {
        QwenProfile p = QwenProfile.Get(profile);
        DifferentialResult result = Run(p, TestAssets.TestDataPath("qwen-bpe", profile, "differential.jsonl.gz"));
        output.WriteLine(result.Summary);
        Assert.True(result.Failures.Count == 0, result.Summary + "\n" + string.Join("\n", result.Failures.Take(10)));
        Assert.True(result.Encodes >= 1500 && result.Decodes >= 500, result.Summary);
    }

    [Theory]
    [InlineData("kev")]
    [InlineData("chat")]
    public void MatchesReferenceOnExternalDumps(string profile)
    {
        // Optional large runs; without the variable this checks nothing (it must not skip: the
        // release drill fails on skipped tests).
        if (Environment.GetEnvironmentVariable("STARLING_QWEN_DIFFERENTIAL_DIR") is not { Length: > 0 } dir)
        {
            output.WriteLine("STARLING_QWEN_DIFFERENTIAL_DIR not set; no external dumps.");
            return;
        }

        QwenProfile p = QwenProfile.Get(profile);
        string[] files = Directory.GetFiles(dir, $"{profile}-*.jsonl.gz");
        Assert.NotEmpty(files);
        foreach (string file in files)
        {
            DifferentialResult result = Run(p, file);
            output.WriteLine($"{Path.GetFileName(file)}: {result.Summary}");
            Assert.True(result.Failures.Count == 0, result.Summary + "\n" + string.Join("\n", result.Failures.Take(10)));
        }
    }

    internal sealed record DifferentialResult(int Encodes, int Decodes, Dictionary<string, int> PerVariant, List<string> Failures)
    {
        public string Summary =>
            $"{Encodes} encodes ({string.Join(", ", PerVariant.Select(kv => $"{kv.Key} {kv.Value}"))}), {Decodes} decodes, {Failures.Count} mismatches";
    }

    internal static DifferentialResult Run(QwenProfile profile, string dumpPath)
    {
        string assetPath = TestAssets.RequireAsset(profile.Asset);
        var tokenizers = new Dictionary<string, Tokenizer>();
        Tokenizer Variant(string name)
        {
            if (!tokenizers.TryGetValue(name, out Tokenizer? t))
            {
                t = name == "asset" ? profile.Load() : Tokenizer.FromUtf8Json(VariantJson(File.ReadAllText(assetPath), name));
                tokenizers[name] = t;
            }

            return t;
        }

        int encodes = 0;
        int decodes = 0;
        var perVariant = new Dictionary<string, int>();
        var failures = new List<string>();
        using var stream = new GZipStream(File.OpenRead(dumpPath), CompressionMode.Decompress);
        using var reader = new StreamReader(stream, new UTF8Encoding(false, true));
        // Lines are compact JSON: raw CR and LF are escaped, so ReadLine (CR, LF, CRLF) splits rows
        // only; U+0085 and U+2028 inside strings are not line breaks for it.
        while (reader.ReadLine() is { } line)
        {
            if (line.Length == 0)
            {
                continue;
            }

            using JsonDocument doc = JsonDocument.Parse(line);
            JsonElement row = doc.RootElement;
            string v = row.GetProperty("v").GetString()!;
            if (v == "header")
            {
                Assert.Equal(profile.Name, row.GetProperty("profile").GetString());
                Assert.Equal(profile.Asset.Sha256, row.GetProperty("asset_sha256").GetString());
                continue;
            }

            if (v == "decode")
            {
                decodes++;
                int[] ids = FixtureAssert.Ints(row.GetProperty("dec"));
                Tokenizer t = Variant("asset");
                Check(failures, $"decode [{string.Join(',', ids)}] keep", row.GetProperty("dk").GetString(), t.Decode(ids, skipSpecialTokens: false));
                Check(failures, $"decode [{string.Join(',', ids)}] skip", row.GetProperty("ds").GetString(), t.Decode(ids, skipSpecialTokens: true));
                continue;
            }

            encodes++;
            perVariant[v] = perVariant.GetValueOrDefault(v) + 1;
            Tokenizer tokenizer = Variant(v);
            string text = row.GetProperty("t").GetString()!;
            string? pair = row.TryGetProperty("p", out JsonElement pe) ? pe.GetString() : null;
            TokenEncoding enc = pair is null ? tokenizer.Encode(text) : tokenizer.Encode(text, pair);
            string label = $"{v} {JsonSerializer.Serialize(text)}{(pair is null ? string.Empty : " + " + JsonSerializer.Serialize(pair))}";
            int[] expectedIds = FixtureAssert.Ints(row.GetProperty("ids"));
            if (!expectedIds.SequenceEqual(enc.Ids))
            {
                failures.Add($"{label}: ids expected [{string.Join(',', expectedIds)}] actual [{string.Join(',', enc.Ids)}]");
                continue;
            }

            int[] flat = FixtureAssert.Ints(row.GetProperty("o"));
            int?[]? seq = row.TryGetProperty("seq", out JsonElement se)
                ? [.. se.EnumerateArray().Select(e => e.ValueKind == JsonValueKind.Null ? (int?)null : e.GetInt32())]
                : null;
            for (int i = 0; i < enc.Count; i++)
            {
                var scalar = new TokenOffset(flat[2 * i], flat[(2 * i) + 1]);
                string source = seq is not null && seq[i] == 1 ? pair! : text;
                TokenOffset utf16 = ScalarToUtf16(source, scalar);
                if (enc.ScalarOffsets[i] != scalar || enc.Offsets[i] != utf16)
                {
                    failures.Add($"{label}: token {i} offsets expected {scalar}/{utf16} actual {enc.ScalarOffsets[i]}/{enc.Offsets[i]}");
                    break;
                }
            }

            if (seq is not null && !seq.SequenceEqual(enc.SequenceIds))
            {
                failures.Add($"{label}: sequence ids differ");
            }

            Check(failures, label + " decode", row.GetProperty("dk").GetString(), tokenizer.Decode(enc.Ids.AsSpan(), skipSpecialTokens: false));
        }

        return new DifferentialResult(encodes, decodes, perVariant, failures);
    }

    /// <summary>The option variants the runner builds (<c>variants</c> in run_qwen_bpe_tokenizer.py), as exact text edits.</summary>
    internal static byte[] VariantJson(string asset, string variant)
    {
        const string post = "\"post_processor\": {\n    \"type\": \"ByteLevel\",\n    \"add_prefix_space\": false,\n    \"trim_offsets\": false,";
        const string pre = "{\n        \"type\": \"ByteLevel\",\n        \"add_prefix_space\": false,";
        string edited = variant switch
        {
            "post-trim-offsets" => ReplaceOnce(asset, post, post.Replace("\"trim_offsets\": false", "\"trim_offsets\": true", StringComparison.Ordinal)),
            "prefix-space-trim" => ReplaceOnce(
                ReplaceOnce(asset, post, post.Replace("false", "true", StringComparison.Ordinal)),
                pre,
                pre.Replace("false", "true", StringComparison.Ordinal)),
            "ignore-merges" => ReplaceOnce(asset, "\"ignore_merges\": false,", "\"ignore_merges\": true,"),
            _ => throw new XunitException($"unknown variant {variant}"),
        };
        return Encoding.UTF8.GetBytes(edited);
    }

    private static string ReplaceOnce(string text, string from, string to)
    {
        int at = text.IndexOf(from, StringComparison.Ordinal);
        Assert.True(at >= 0 && text.IndexOf(from, at + 1, StringComparison.Ordinal) < 0, $"expected exactly one '{from}'");
        return string.Concat(text.AsSpan(0, at), to, text.AsSpan(at + from.Length));
    }

    private static TokenOffset ScalarToUtf16(string text, TokenOffset scalar)
    {
        int ToUtf16(int s)
        {
            int units = 0;
            int count = 0;
            foreach (Rune r in text.EnumerateRunes())
            {
                if (count == s)
                {
                    break;
                }

                units += r.Utf16SequenceLength;
                count++;
            }

            return units;
        }

        return new TokenOffset(ToUtf16(scalar.Start), ToUtf16(scalar.End));
    }

    private static void Check(List<string> failures, string label, string? expected, string actual)
    {
        if (!string.Equals(expected, actual, StringComparison.Ordinal))
        {
            failures.Add($"{label}: expected {JsonSerializer.Serialize(expected)} actual {JsonSerializer.Serialize(actual)}");
        }
    }
}
