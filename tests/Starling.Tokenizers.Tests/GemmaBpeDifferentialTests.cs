using System.IO.Compression;
using System.Text;
using System.Text.Json;
using Xunit.Sdk;

namespace Starling.Tokenizers.Tests;

/// <summary>
/// Randomized differential test of profile <c>gemma-bpe-embeddinggemma2</c> against
/// huggingface/tokenizers 0.23.3 (the Rust implementation through its Python binding; the version the
/// accepted fixtures were generated with). The dumps hold seeded generated strings (byte-fallback-heavy
/// rare scripts, private use, controls, emoji, astral planes, whitespace runs, <c>▁</c> and byte-token
/// look-alikes, added-token literals and fragments) with the reference ids, offsets and decode, on the
/// asset and on option variants (text edits of the asset listed in the dump header), plus random id
/// sequences for decode. Generated by reference/gemma-bpe/run_gemma_bpe_tokenizer.py.
/// </summary>
/// <remarks>
/// The committed dump (<c>TestData/gemma-bpe/differential.jsonl.gz</c>: 2,000 strings, 300 per variant,
/// 1,000 decodes, seed 20261011) always runs. Larger dumps are kept outside Git: set
/// <c>STARLING_GEMMA_DIFFERENTIAL_DIR</c> to a directory of <c>gemma-*.jsonl.gz</c> files from the same
/// runner and they run too.
/// </remarks>
public class GemmaBpeDifferentialTests(ITestOutputHelper output)
{
    [Fact]
    public void MatchesReferenceOnCommittedDump()
    {
        DifferentialResult result = Run(TestAssets.TestDataPath("gemma-bpe", "differential.jsonl.gz"));
        output.WriteLine(result.Summary);
        Assert.True(result.Failures.Count == 0, result.Summary + "\n" + string.Join("\n", result.Failures.Take(10)));
        Assert.True(result.Encodes >= 2000 && result.Decodes >= 1000 && result.PerVariant.Count == 11, result.Summary);
    }

    [Fact]
    public void MatchesReferenceOnExternalDumps()
    {
        // Optional large runs; without the variable this checks nothing (it must not skip: the
        // release drill fails on skipped tests).
        if (Environment.GetEnvironmentVariable("STARLING_GEMMA_DIFFERENTIAL_DIR") is not { Length: > 0 } dir)
        {
            output.WriteLine("STARLING_GEMMA_DIFFERENTIAL_DIR not set; no external dumps.");
            return;
        }

        string[] files = Directory.GetFiles(dir, "gemma-*.jsonl.gz");
        Assert.NotEmpty(files);
        foreach (string file in files)
        {
            DifferentialResult result = Run(file);
            output.WriteLine($"{Path.GetFileName(file)}: {result.Summary}");
            Assert.True(result.Failures.Count == 0, result.Summary + "\n" + string.Join("\n", result.Failures.Take(10)));
        }
    }

    internal sealed record DifferentialResult(int Encodes, int Decodes, Dictionary<string, int> PerVariant, List<string> Failures)
    {
        public string Summary =>
            $"{Encodes} encodes ({string.Join(", ", PerVariant.Select(kv => $"{kv.Key} {kv.Value}"))}), {Decodes} decodes, {Failures.Count} mismatches";
    }

    internal static DifferentialResult Run(string dumpPath)
    {
        string assetPath = TestAssets.RequireAsset(TestAssets.EmbeddingGemma2TokenizerJson);
        string? assetText = null;
        var tokenizers = new Dictionary<string, Tokenizer>();
        Dictionary<string, JsonElement> variants = [];
        Tokenizer Variant(string name)
        {
            if (!tokenizers.TryGetValue(name, out Tokenizer? t))
            {
                if (name == "asset")
                {
                    t = TestAssets.LoadTokenizer(TestAssets.EmbeddingGemma2TokenizerJson);
                }
                else
                {
                    assetText ??= File.ReadAllText(assetPath);
                    t = Tokenizer.FromUtf8Json(Encoding.UTF8.GetBytes(ApplyEdits(assetText, variants[name])));
                }

                tokenizers[name] = t;
            }

            return t;
        }

        int encodes = 0;
        int decodes = 0;
        var perVariant = new Dictionary<string, int>();
        var failures = new List<string>();
        using var stream = new GZipStream(File.OpenRead(dumpPath), CompressionMode.Decompress);
        using var reader = new StreamReader(stream, new UTF8Encoding(false, true));
        bool sawHeader = false;

        // Lines are compact JSON: raw CR and LF are escaped, so ReadLine (CR, LF, CRLF) splits rows
        // only; U+0085 and U+2028 inside strings are not line breaks for it.
        while (reader.ReadLine() is { } line)
        {
            if (line.Length == 0)
            {
                continue;
            }

            using JsonDocument doc = JsonDocument.Parse(line);
            JsonElement row = doc.RootElement;
            string v = row.GetProperty("v").GetString()!;
            if (v == "header")
            {
                Assert.Equal("gemma-bpe-embeddinggemma2", row.GetProperty("profile").GetString());
                Assert.Equal(TestAssets.EmbeddingGemma2TokenizerJson.Sha256, row.GetProperty("asset_sha256").GetString());
                Assert.StartsWith("tokenizers 0.23.", row.GetProperty("reference").GetString(), StringComparison.Ordinal);
                foreach (JsonProperty p in row.GetProperty("variants").EnumerateObject())
                {
                    variants[p.Name] = p.Value.Clone();
                }

                sawHeader = true;
                continue;
            }

            Assert.True(sawHeader, "dump has no header row");
            if (v == "decode")
            {
                decodes++;
                int[] ids = FixtureAssert.Ints(row.GetProperty("dec"));
                Tokenizer t = Variant("asset");
                Check(failures, $"decode [{string.Join(',', ids)}] keep", row.GetProperty("dk").GetString(), t.Decode(ids, skipSpecialTokens: false));
                Check(failures, $"decode [{string.Join(',', ids)}] skip", row.GetProperty("ds").GetString(), t.Decode(ids, skipSpecialTokens: true));
                continue;
            }

            encodes++;
            perVariant[v] = perVariant.GetValueOrDefault(v) + 1;
            Tokenizer tokenizer = Variant(v);
            string text = row.GetProperty("t").GetString()!;
            string? pair = row.TryGetProperty("p", out JsonElement pe) ? pe.GetString() : null;
            TokenEncoding enc = pair is null ? tokenizer.Encode(text) : tokenizer.Encode(text, pair);
            string label = $"{v} {JsonSerializer.Serialize(text)}{(pair is null ? string.Empty : " + " + JsonSerializer.Serialize(pair))}";
            int[] expectedIds = FixtureAssert.Ints(row.GetProperty("ids"));
            if (!expectedIds.SequenceEqual(enc.Ids))
            {
                failures.Add($"{label}: ids expected [{string.Join(',', expectedIds)}] actual [{string.Join(',', enc.Ids)}]");
                continue;
            }

            int[] flat = FixtureAssert.Ints(row.GetProperty("o"));
            int?[]? seq = row.TryGetProperty("seq", out JsonElement se)
                ? [.. se.EnumerateArray().Select(e => e.ValueKind == JsonValueKind.Null ? (int?)null : e.GetInt32())]
                : null;
            for (int i = 0; i < enc.Count; i++)
            {
                var scalar = new TokenOffset(flat[2 * i], flat[(2 * i) + 1]);
                string source = seq is not null && seq[i] == 1 ? pair! : text;
                TokenOffset utf16 = ScalarToUtf16(source, scalar);
                if (enc.ScalarOffsets[i] != scalar || enc.Offsets[i] != utf16)
                {
                    failures.Add($"{label}: token {i} offsets expected {scalar}/{utf16} actual {enc.ScalarOffsets[i]}/{enc.Offsets[i]}");
                    break;
                }
            }

            if (seq is not null && !seq.SequenceEqual(enc.SequenceIds))
            {
                failures.Add($"{label}: sequence ids differ");
            }

            Check(failures, label + " decode", row.GetProperty("dk").GetString(), tokenizer.Decode(enc.Ids.AsSpan(), skipSpecialTokens: false));
        }

        return new DifferentialResult(encodes, decodes, perVariant, failures);
    }

    /// <summary>The runner's <c>apply_edits</c>: exact text edits of the pretty-printed asset.</summary>
    internal static string ApplyEdits(string text, JsonElement edits)
    {
        foreach (JsonElement edit in edits.EnumerateArray())
        {
            switch (edit.GetProperty("op").GetString())
            {
                case "replace_once":
                    {
                        string from = edit.GetProperty("from").GetString()!;
                        int at = text.IndexOf(from, StringComparison.Ordinal);
                        Assert.True(at >= 0 && text.IndexOf(from, at + 1, StringComparison.Ordinal) < 0, $"expected exactly one '{from}'");
                        text = string.Concat(text.AsSpan(0, at), edit.GetProperty("to").GetString(), text.AsSpan(at + from.Length));
                        break;
                    }

                case "section":
                    {
                        string marker = $"\n  \"{edit.GetProperty("key").GetString()}\": ";
                        int at = text.IndexOf(marker, StringComparison.Ordinal);
                        Assert.True(at >= 0 && text.IndexOf(marker, at + 1, StringComparison.Ordinal) < 0, $"expected exactly one top-level '{marker.Trim()}'");
                        int start = at + marker.Length;
                        int end = text.IndexOf(",\n  \"", start, StringComparison.Ordinal);
                        text = string.Concat(text.AsSpan(0, start), edit.GetProperty("value").GetRawText(), text.AsSpan(end));
                        break;
                    }

                default:
                    throw new XunitException($"unknown edit {edit}");
            }
        }

        return text;
    }

    internal static TokenOffset ScalarToUtf16(string text, TokenOffset scalar)
    {
        int ToUtf16(int s)
        {
            int units = 0;
            int count = 0;
            foreach (Rune r in text.EnumerateRunes())
            {
                if (count == s)
                {
                    break;
                }

                units += r.Utf16SequenceLength;
                count++;
            }

            return units;
        }

        return new TokenOffset(ToUtf16(scalar.Start), ToUtf16(scalar.End));
    }

    private static void Check(List<string> failures, string label, string? expected, string actual)
    {
        if (!string.Equals(expected, actual, StringComparison.Ordinal))
        {
            failures.Add($"{label}: expected {JsonSerializer.Serialize(expected)} actual {JsonSerializer.Serialize(actual)}");
        }
    }
}
