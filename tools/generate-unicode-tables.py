#!/usr/bin/env python3
"""Generates the Unicode data tables of the owned tokenizer's Qwen byte-level BPE components.

Two generated C# files under src/StarlingHq.Tokenizers/Pipeline/:

- Unicode9NormalizationData.g.cs: canonical combining classes, full canonical decompositions and
  primary compositions from the crate unicode-normalization-alignments 0.1.12 (src/tables.rs,
  Unicode 9.0.0), the crate huggingface/tokenizers 0.23.2 uses for its NFC normalizer. The reference
  normalizes with Unicode 9.0.0 data, not with the runtime's, so the tables are copied rather than
  taken from .NET's string.Normalize (Unicode 16).
- RegexUnicodeClassData.g.cs: the code points that the reference's regex engine (Oniguruma, in
  tokenizers 0.23.2) matches with \\p{L}, \\p{N} and \\p{M}, as inclusive ranges. Input: the
  unicode-classes.json written by reference/qwen-bpe/run_qwen_bpe_tokenizer.py
  --unicode-classes, which probes every Unicode scalar value through the reference.

Usage:
    curl -L https://crates.io/api/v1/crates/unicode-normalization-alignments/0.1.12/download -o una.crate
    tools/generate-unicode-tables.py --crate una.crate --classes unicode-classes.json
"""

from __future__ import annotations

import argparse
import hashlib
import io
import json
import re
import tarfile
from pathlib import Path

CRATE_SHA256 = "43f613e4fa046e69818dd287fdc4bc78175ff20331479dab6e1b0f98d57062de"
ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src/StarlingHq.Tokenizers/Pipeline"


def char_value(literal: str) -> int:
    m = re.fullmatch(r"'\\u\{([0-9A-Fa-f]+)\}'", literal)
    if not m:
        raise ValueError(literal)
    return int(m.group(1), 16)


def table_body(source: str, name: str) -> str:
    start = source.index(f"pub(crate) const {name}")
    start = source.index("&[", start) + 2
    end = source.index("\n];", start)
    return source[start:end]


def parse_tables(tables_rs: str) -> tuple[dict[int, int], dict[int, list[int]], dict[tuple[int, int], int]]:
    if "pub const UNICODE_VERSION: (u64, u64, u64) = (9, 0, 0);" not in tables_rs:
        raise ValueError("unexpected Unicode version in tables.rs")
    ccc = {}
    for m in re.finditer(r"0x([0-9A-Fa-f]+),", table_body(tables_rs, "CANONICAL_COMBINING_CLASS_KV")):
        kv = int(m.group(1), 16)
        ccc[kv >> 8] = kv & 0xFF
    decomposed = {}
    for m in re.finditer(r"\(0x([0-9A-Fa-f]+), &\[([^\]]*)\]\)", table_body(tables_rs, "CANONICAL_DECOMPOSED_KV")):
        decomposed[int(m.group(1), 16)] = [char_value(c.strip()) for c in m.group(2).split(",") if c.strip()]
    composed = {}
    for m in re.finditer(r"\(0x([0-9A-Fa-f]+), ('[^']+')\)", table_body(tables_rs, "COMPOSITION_TABLE_KV")):
        key = int(m.group(1), 16)
        composed[(key >> 16, key & 0xFFFF)] = char_value(m.group(2))
    astral = tables_rs[tables_rs.index("fn composition_table_astral") :]
    astral = astral[: astral.index("_ => None")]
    for m in re.finditer(r"\(('[^']+'), ('[^']+')\) => Some\(('[^']+')\)", astral):
        composed[(char_value(m.group(1)), char_value(m.group(2)))] = char_value(m.group(3))
    return ccc, decomposed, composed


def ints(values: list[int], per_line: int = 12) -> str:
    lines = []
    for i in range(0, len(values), per_line):
        lines.append("        " + ", ".join(f"0x{v:X}" for v in values[i : i + per_line]) + ",")
    return "\n".join(lines)


HEADER = """// <auto-generated>
// Generated by tools/generate-unicode-tables.py. Do not edit by hand.
// </auto-generated>
"""


def write_normalization(ccc, decomposed, composed) -> None:
    ccc_entries = [(cp << 8) | value for cp, value in sorted(ccc.items()) if value != 0]
    index, chars = [], []
    for cp in sorted(decomposed):
        index += [cp, len(chars), len(decomposed[cp])]
        chars += decomposed[cp]
    comp = []
    for (a, b), c in sorted(composed.items()):
        comp += [a, b, c]
    text = f"""{HEADER}//
// Data: crate unicode-normalization-alignments 0.1.12 (MIT OR Apache-2.0), src/tables.rs, generated
// by that crate from the Unicode Character Database 9.0.0 (Unicode License V3). See
// THIRD-PARTY-NOTICES.md and PROVENANCE.md. huggingface/tokenizers 0.23.2 normalizes NFC with this
// crate, so these Unicode 9.0.0 values, not the runtime's, are the reference behavior.

namespace StarlingHq.Tokenizers.Pipeline;

internal static class Unicode9NormalizationData
{{
    /// <summary>Non-zero canonical combining classes as <c>(code point &lt;&lt; 8) | class</c>, sorted.</summary>
    public static ReadOnlySpan<int> CombiningClasses =>
    [
{ints(ccc_entries)}
    ];

    /// <summary>Full canonical decompositions: <c>code point, start, length</c> triples into <see cref="DecompositionChars"/>, sorted.</summary>
    public static ReadOnlySpan<int> DecompositionIndex =>
    [
{ints(index)}
    ];

    public static ReadOnlySpan<int> DecompositionChars =>
    [
{ints(chars)}
    ];

    /// <summary>Primary compositions (Hangul excluded): <c>first, second, composite</c> triples, sorted.</summary>
    public static ReadOnlySpan<int> Compositions =>
    [
{ints(comp)}
    ];
}}
"""
    (OUT / "Unicode9NormalizationData.g.cs").write_text(text, encoding="utf-8", newline="\n")
    print(f"ccc {len(ccc_entries)}, decompositions {len(decomposed)}, compositions {len(composed)}")


def write_classes(classes: dict) -> None:
    parts = []
    for name, doc in [("L", "Letter"), ("N", "Number"), ("M", "Mark")]:
        flat = [v for r in classes["classes"][name] for v in r]
        parts.append(
            f"""    /// <summary><c>\\p{{{name}}}</c>: inclusive <c>start, end</c> ranges, sorted.</summary>
    public static ReadOnlySpan<int> {doc}Ranges =>
    [
{ints(flat)}
    ];
"""
        )
    white = [c for r in classes["classes"]["s"] for c in range(r[0], r[1] + 1)]
    text = f"""{HEADER}//
// Data: the code points the regex engine of huggingface/tokenizers 0.23.2 (Oniguruma, crate onig_sys
// 69.9.3) matches with \\p{{L}}, \\p{{N}} and \\p{{M}}, probed over every Unicode scalar value by
// reference/qwen-bpe/run_qwen_bpe_tokenizer.py --unicode-classes ({classes["engine"]}).
// Unicode Character Database general categories (Unicode License V3); see THIRD-PARTY-NOTICES.md.
// \\s matched exactly these {len(white)} code points: {", ".join(f"U+{c:04X}" for c in white)}.

namespace StarlingHq.Tokenizers.Pipeline;

internal static class RegexUnicodeClassData
{{
{chr(10).join(parts)}}}
"""
    (OUT / "RegexUnicodeClassData.g.cs").write_text(text, encoding="utf-8", newline="\n")
    print({k: len(v) for k, v in classes["classes"].items()})


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--crate", type=Path, required=True)
    parser.add_argument("--classes", type=Path, required=True)
    args = parser.parse_args()
    data = args.crate.read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    if digest != CRATE_SHA256:
        raise SystemExit(f"{args.crate}: sha256 {digest}, expected {CRATE_SHA256}")
    with tarfile.open(fileobj=io.BytesIO(data), mode="r:gz") as tar:
        member = tar.extractfile("unicode-normalization-alignments-0.1.12/src/tables.rs")
        tables_rs = member.read().decode("utf-8")
    write_normalization(*parse_tables(tables_rs))
    write_classes(json.loads(args.classes.read_text(encoding="utf-8")))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
